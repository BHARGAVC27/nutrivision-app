import type { MaczCategory, Sex } from '../pipeline/zscore';
import tablesJson from './tables.json';

/**
 * Stage 5 (extension) — after the screen: which deficiencies are common for a
 * child like this one, and what should they eat today?
 *
 * Ported from the research repo's `nutrition_ext/scripts/india_risk.py` and
 * `food_plan.py`; the full record is `NUTRITION_EXTENSION.md`. It replaces
 * nothing upstream. Inputs: age, sex, the screening category, and one optional
 * answer — diet type. Table lookups, one formula and a scored menu out; no model.
 *
 *   1. The category routes the advice. Severe → refer now, no home diet (WHO
 *      2013). Moderate → where to get extra food, by age (Anganwadi under 6 y,
 *      school midday meal 6–14 y, health centre), plus the plan. Otherwise the
 *      plan. Under 6 months: breast milk only.
 *   2. Risk for 7 deficiencies from CNNS 2016–18, India's national blood-test
 *      survey. CNNS publishes one-way tables, so the child's age sub-group, sex
 *      and (if given) diet rates are combined around the age-band total:
 *
 *        logit(risk) = logit(total) + λ · Σ_k [logit(rate_k) − logit(total)]
 *
 *      with λ ≈ 0.89 fitted on NHANES cross-tabs. Flagged at ≥ 20 in 100, WHO's
 *      public-health level. These say how common each deficiency is among
 *      children like this one — not a test of this child — and they do not
 *      depend on the arm: in NHANES, body size added < 0.01 AUROC.
 *   3. The daily plan is the child's row of ICMR-NIN DGI 2024 Annexure V.
 *   4. One menu: for each Annexure V slot, the IFCT 2017 food that helps all
 *      flagged nutrients together when eaten as that slot's allowance, scored
 *      as Σ amount / best-amount-in-slot over the flagged measures, plus two
 *      alternatives. Diet filters the foods; skipped, the child is assumed
 *      non-vegetarian (foods) and the risks use all children.
 *
 * `tables.json` is generated by `scripts/make-nutrition-tables.py`;
 * `scripts/verify-nutrition.ts` checks this file against the Python engine
 * for every age 3–228 months × sex × diet answer.
 */

export type Diet = 'veg' | 'egg' | 'nonveg';
export type Nutrient = 'anaemia' | 'iron_def' | 'vitD_def' | 'zinc_def' | 'vitA_def' | 'folate_def' | 'b12_def';
export type Measure = 'iron' | 'zinc' | 'folate' | 'vitA' | 'vitD';
export type FoodGroup = 'A' | 'B' | 'C' | 'D' | 'E' | 'F' | 'H' | 'J' | 'L' | 'M' | 'N' | 'O' | 'P' | 'Q' | 'R' | 'S';
export type SlotId = 'millets' | 'pulses' | 'glv' | 'vegetables' | 'roots' | 'fruits' | 'nuts' | 'milk' | 'swap';
export type PlanColumn =
  | 'cereals_millets_g'
  | 'pulses_g'
  | 'glv_g'
  | 'vegetables_g'
  | 'roots_tubers_g'
  | 'fruits_g'
  | 'nuts_g'
  | 'milk_curd_ml'
  | 'fats_oils_g';
export type NutrientColumn = 'fe' | 'zn' | 'folsum' | 'retol' | 'cartb' | 'vitd';
export type ActionKey = 'refer' | 'infant' | 'infant_mod' | 'mod_anganwadi' | 'mod_school' | 'mod_health' | 'plan';
type AgeBand = '1-4' | '5-9' | '10-19';
type Rate = [rate: number, table: string];
type Need = 'all' | 'egg' | 'nonveg';

/** One Annexure V row. `milk_curd_ml` is null on the 7–12 month row, which says "breast milk". */
export type PlanRow = {
  ageGroup: string;
  sex: 'm' | 'f' | 'any';
  ageMin: number;
  ageMax: number;
  energyKcal: number | null;
  proteinG: number | null;
} & Record<PlanColumn, number | null>;

/** An IFCT 2017 food; nutrient columns are grams per 100 g edible portion. */
export type Food = {
  code: string;
  /** IFCT 2017 name, kept for traceability. */
  name: string;
  /** Plain name for the screen. */
  display: string;
  group: FoodGroup;
  need: Need;
  /** First name for the language in IFCT's "Local Name" column, in Latin script. */
  local: Record<'hi' | 'kn' | 'ta' | 'te', string | null>;
} & Record<NutrientColumn, number | null>;

type Spec = { col: NutrientColumn; mult: number; unit: string; groups: FoodGroup[] | null };
type Tables = {
  version: string;
  lambda: number;
  flagAt: number;
  milletShare: number;
  swapG: number;
  eggG: number;
  swapGroups: FoodGroup[];
  nutrients: Nutrient[];
  nutrientMeasure: Record<Nutrient, Measure | null>;
  measures: Record<Measure, Spec[]>;
  slots: { slot: SlotId; col: PlanColumn; groups: FoodGroup[] }[];
  allowed: Record<Diet, Need[]>;
  cnns: Record<
    Nutrient,
    Record<AgeBand, { total: Rate; age: Record<string, Rate>; sex: { Male?: Rate; Female?: Rate }; diet: Record<string, Rate> }>
  >;
  plan: PlanRow[];
  foods: Food[];
};

const T = tablesJson as unknown as Tables;

/** The CNNS rows a risk was built from, for the "how we got this" box. */
export type RiskSource = { kind: 'total' | 'age' | 'sex' | 'diet'; category: string; rate: number; table: string };
export type Risk = { nutrient: Nutrient; risk: number; flagged: boolean; sources: RiskSource[] };

export type MenuFood = {
  food: Food;
  /** Grams (ml for milk) of the slot's daily allowance it fills. */
  portion: number;
  /** Combined score over the flagged measures (0–1 per measure). */
  score: number;
  /** What it supplies in that portion, per IFCT column with a positive amount. */
  amounts: Partial<Record<NutrientColumn, number>>;
};
export type MenuSlot = { slot: SlotId; grams: number; foods: MenuFood[] };

export type FoodPlan = {
  action: ActionKey;
  moderate: boolean;
  /** The diet the foods follow; `dietAsked` says whether it was answered or assumed. */
  diet: Diet;
  dietAsked: boolean;
  /** Null when there is no plan (refer now, or under 6 months). */
  row: PlanRow | null;
  risks: Risk[] | null;
  menu: MenuSlot[];
  /** What the menu's first choices give, per IFCT column. */
  totals: Partial<Record<NutrientColumn, number>>;
};

export const FLAG_AT = T.flagAt;
export const LAMBDA = T.lambda;
export const TABLES_VERSION = T.version;
export const DEFAULT_DIET: Diet = 'nonveg';
export const DIET_LABEL: Record<Diet, string> = { veg: 'Vegetarian', egg: 'Vegetarian with egg', nonveg: 'Non-vegetarian' };
/** Measure units by IFCT column, as the tables state them. */
export const COLUMN_UNIT: Record<NutrientColumn, string> = Object.fromEntries(
  Object.values(T.measures).flatMap((specs) => specs.map((s) => [s.col, s.unit]))
) as Record<NutrientColumn, string>;

function logit(p: number): number {
  const q = Math.min(Math.max(p, 1e-4), 1 - 1e-4);
  return Math.log(q / (1 - q));
}

function expit(x: number): number {
  return 1 / (1 + Math.exp(-x));
}

function ageBand(ageMonths: number): AgeBand | null {
  if (ageMonths < 12) return null;
  return ageMonths < 60 ? '1-4' : ageMonths < 120 ? '5-9' : '10-19';
}

/** CNNS age sub-group label, exactly as the report's tables print it. */
function ageSubgroup(ageMonths: number): string | null {
  if (ageMonths < 60) {
    for (const [lo, hi] of [[12, 17], [18, 23], [24, 35], [36, 47], [48, 59]]) {
      if (lo <= ageMonths && ageMonths <= hi) return `${lo}–${hi}`;
    }
    return null;
  }
  const years = Math.floor(ageMonths / 12);
  if (years < 10) return years <= 7 ? '5–7' : '8–9';
  return years <= 14 ? '10–14' : '15–19';
}

/** Risk for each of the 7 deficiencies, or null under 12 months (outside CNNS). */
export function deficiencyRisks(ageMonths: number, sex: Sex, diet: Diet | null = null): Risk[] | null {
  const band = ageBand(ageMonths);
  if (!band) return null;
  const sub = ageSubgroup(ageMonths);
  const sexKey = sex === 'M' ? 'Male' : 'Female';
  return T.nutrients.map((nutrient) => {
    const rates = T.cnns[nutrient][band];
    const [total, totalTable] = rates.total;
    const sources: RiskSource[] = [{ kind: 'total', category: band, rate: total, table: totalTable }];
    const parts: [RiskSource['kind'], string, Rate | undefined][] = [
      ['age', sub ?? '', sub ? rates.age[sub] : undefined],
      ['sex', sexKey, rates.sex[sexKey]],
    ];
    if (diet) parts.push(['diet', DIET_LABEL[diet], rates.diet[DIET_LABEL[diet]]]);
    let dev = 0;
    for (const [kind, category, r] of parts) {
      if (!r) continue; // CNNS suppresses cells with N < 50
      dev += logit(r[0]) - logit(total);
      sources.push({ kind, category, rate: r[0], table: r[1] });
    }
    const risk = expit(logit(total) + T.lambda * dev);
    return { nutrient, risk, flagged: risk >= T.flagAt, sources };
  });
}

export function planRow(ageMonths: number, sex: Sex): PlanRow | null {
  const s = sex === 'M' ? 'm' : 'f';
  return T.plan.find((r) => r.ageMin <= ageMonths && r.ageMax >= ageMonths && (r.sex === s || r.sex === 'any')) ?? null;
}

/** Distinct measures of the flagged nutrients, in nutrient order (iron counted once). */
export function flaggedMeasures(risks: Risk[]): Measure[] {
  const out: Measure[] = [];
  for (const r of risks) {
    const m = T.nutrientMeasure[r.nutrient];
    if (r.flagged && m && !out.includes(m)) out.push(m);
  }
  return out;
}

/** Top 3 foods for one slot by the combined score; [] if no flagged measure applies. */
function menuSlot(groups: FoodGroup[], portionOf: (g: FoodGroup) => number, measures: Measure[], diet: Diet): MenuFood[] {
  const allowed = T.allowed[diet];
  const cands = T.foods.filter((f) => groups.includes(f.group) && allowed.includes(f.need));
  if (!cands.length) return [];
  const portions = cands.map((f) => portionOf(f.group));
  const score = cands.map(() => 0);
  const amounts = cands.map(() => ({}) as Partial<Record<NutrientColumn, number>>);
  for (const m of measures) {
    const total = cands.map(() => 0);
    for (const { col, mult, groups: specGroups } of T.measures[m]) {
      cands.forEach((f, i) => {
        const v = f[col];
        const ok = v != null && v > 0 && (!specGroups || specGroups.includes(f.group));
        const a = ok ? (v * mult * portions[i]) / 100 : 0;
        total[i] += a;
        if (a > 0) amounts[i][col] = a;
      });
    }
    const best = Math.max(...total);
    if (best > 0) total.forEach((t, i) => (score[i] += t / best));
  }
  const order = cands
    .map((_, i) => i)
    .filter((i) => score[i] > 0)
    .sort((a, b) => score[b] - score[a] || (cands[a].code < cands[b].code ? -1 : cands[a].code > cands[b].code ? 1 : 0));
  return order.slice(0, 3).map((i) => ({ food: cands[i], portion: portions[i], score: score[i], amounts: amounts[i] }));
}

function dailyMenu(row: PlanRow, risks: Risk[], diet: Diet): { menu: MenuSlot[]; totals: FoodPlan['totals'] } {
  const measures = flaggedMeasures(risks);
  if (!measures.length) return { menu: [], totals: {} };
  const swap = diet === 'egg' || diet === 'nonveg';
  const menu: MenuSlot[] = T.slots.map(({ slot, col, groups }) => {
    let grams = row[col] as number;
    if (slot === 'millets') grams = grams * T.milletShare;
    if (slot === 'pulses' && swap) grams = grams - T.swapG;
    return { slot, grams, foods: menuSlot(groups, () => grams, measures, diet) };
  });
  if (swap) {
    menu.push({ slot: 'swap', grams: T.swapG, foods: menuSlot(T.swapGroups, (g) => (g === 'M' ? T.eggG : T.swapG), measures, diet) });
  }
  const totals: FoodPlan['totals'] = {};
  for (const s of menu) {
    const top = s.foods[0];
    if (!top) continue;
    for (const [c, a] of Object.entries(top.amounts) as [NutrientColumn, number][]) totals[c] = (totals[c] ?? 0) + a;
  }
  return { menu, totals };
}

function actionKey(category: MaczCategory, ageMonths: number): ActionKey {
  if (category === 'severe') return 'refer';
  if (ageMonths < 6) return category === 'moderate' ? 'infant_mod' : 'infant';
  if (category !== 'moderate') return 'plan';
  return ageMonths < 72 ? 'mod_anganwadi' : ageMonths < 168 ? 'mod_school' : 'mod_health';
}

/** The amounts of one daily plan, without the Annexure V row's own labels. */
export type PlanAmounts = Omit<PlanRow, 'ageGroup' | 'sex' | 'ageMin' | 'ageMax'>;

/**
 * Merged app: the same risks and menu as `foodPlan`, but each slot filled
 * with the child's own weight-adjusted amounts from `diet/plan.ts` (catch-up
 * food included) instead of the fixed Annexure V row, so the diet plan and
 * the menu never disagree. Given for every category: the team chose a full
 * plan even for Refer, alongside the "go to the health centre" message, so
 * `action` still says where the child must go. Under 6 months: breast milk only.
 */
export function foodPlanForAmounts(ageMonths: number, sex: Sex, category: MaczCategory, diet: Diet | null, amounts: PlanAmounts): FoodPlan {
  const action = actionKey(category, ageMonths);
  const base = { action, moderate: category === 'moderate', diet: diet ?? DEFAULT_DIET, dietAsked: diet != null };
  if (ageMonths < 6) return { ...base, row: null, risks: null, menu: [], totals: {} };
  const ref = planRow(ageMonths, sex);
  const row: PlanRow = { ageGroup: ref?.ageGroup ?? '', sex: ref?.sex ?? 'any', ageMin: ref?.ageMin ?? ageMonths, ageMax: ref?.ageMax ?? ageMonths, ...amounts };
  const risks = deficiencyRisks(ageMonths, sex, diet);
  const { menu, totals } = risks ? dailyMenu(row, risks, base.diet) : { menu: [], totals: {} };
  return { ...base, row, risks, menu, totals };
}

export function foodPlan(ageMonths: number, sex: Sex, category: MaczCategory, diet: Diet | null = null): FoodPlan {
  const action = actionKey(category, ageMonths);
  const base = { action, moderate: category === 'moderate', diet: diet ?? DEFAULT_DIET, dietAsked: diet != null };
  const row = planRow(ageMonths, sex);
  if (action === 'refer' || action === 'infant' || action === 'infant_mod' || !row) {
    return { ...base, row: null, risks: null, menu: [], totals: {} };
  }
  const risks = deficiencyRisks(ageMonths, sex, diet);
  const { menu, totals } = risks ? dailyMenu(row, risks, base.diet) : { menu: [], totals: {} };
  return { ...base, row, risks, menu, totals };
}
